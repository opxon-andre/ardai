export function makeT(language = 'en', brand = DEFAULT_BRAND) {
  const lang = TEXTS[language] ? language : 'en';
  return (key, vars = {}) => {
    const s = TEXTS[lang][key] ?? TEXTS.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? (k === 'app' ? brand.name : k === 'cli' ? brand.cli : `{${k}}`)));
  };
}
